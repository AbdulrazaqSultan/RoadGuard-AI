"""Run the Stage 7 vehicle pipeline or review an archived run."""

from pathlib import Path

from roadguard.cli import config_parser, run
from roadguard.config import load_config
from roadguard.utils.paths import project_root
from roadguard.vehicle.stage7 import PROFILE, checked_source, run_stage7


def main() -> None:
    parser = config_parser(__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--video", type=Path)
    source.add_argument("--camera", type=int)
    source.add_argument("--software-check", action="store_true")
    source.add_argument("--finalize", type=Path)
    parser.add_argument("--mode", choices=("throughput", "realtime"), default="throughput")
    parser.add_argument("--provenance", default="", help="Origin of the independent capture.")
    args = parser.parse_args()
    root = project_root()
    if args.finalize:
        from roadguard.vehicle.review import finalize_stage7

        print(finalize_stage7(root, args.finalize.resolve()))
        return
    config = load_config(
        root,
        profile=args.config or root / PROFILE,
        overrides=args.overrides,
        extra_defaults={"vehicle": "vehicle/default.yaml"},
    )
    if args.software_check:
        input_source = None
        provenance = "Schematic road clip generated by write_software_video with seed 42."
    else:
        input_source = checked_source(root, args.video, args.camera)
        provenance = args.provenance or "Operator-supplied capture; independent origin unverified."
    print(run_stage7(root, config, input_source, args.mode, provenance))


if __name__ == "__main__":
    run(main)
